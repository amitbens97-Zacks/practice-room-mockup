// The row for a new objection, from the patterns above or the sheet's row of its form.
export function suggestLocal(said) {
  const t = said.trim();
  const hit = NEW_ROWS.find((r) => r.re.test(t));
  if (hit) {
    const { re, ...row } = hit;
    return { ...row, src: 'הוספת · נבנה מההצעה וכללי המחיר' };
  }
  const form = (FORM_RE.find(([, re]) => re.test(t)) || ['avoid'])[0];
  const base = ROWS.find((r) => r.form === form);
  return { form, worry: base.worry, ask: base.ask, reply: base.reply, close: base.close, honest: base.honest, short: base.short, src: `הוספת · לפי "${base.said}" בדף` };
}

