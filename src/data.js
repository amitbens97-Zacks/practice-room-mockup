// The one fix: a core dimension under 3 (earliest first), else the earliest stage under 3,
// else the weakest score. scores = [[name, score|null, why], ...] in DIMS order.
export function fixDim(scores) {
  const rows = scores.map((s, i) => ({ i, d: DIMS[i], n: s[1] })).filter((r) => r.n != null);
  const broken = rows.filter((r) => r.n < 3 && r.d.stage != null).sort((a, b) => a.d.stage - b.d.stage);
  const pick = broken.find((r) => r.d.core) || broken[0] || rows.reduce((a, b) => (b.n < a.n ? b : a), rows[0]);
  return pick ? pick.i : -1;
}

